#!/usr/bin/env python3
"""Generate or check deterministic `agents/openai.yaml` UI metadata.

The Agent Skills format stays vendor-neutral; this optional file gives Codex
and ChatGPT a readable title, compact skill-list blurb, and invocation prompt.
Other clients ignore it. Stdlib only. Python 3.9+.

Copy rules (this text is user-facing in Codex and ChatGPT):
  * `display_name`  — the SKILL.md H1.
  * `short_description` — the first clause of the skill's own `description`,
    which is already written third-person verb-first ("Ranks rival
    explanations ..."). Never the literal string "Apply <method>": most
    `metadata.method` values are noun phrases and read ungrammatically after a
    bare verb.
  * `default_prompt` — "Use $<name> to apply <method> ...", where <method> is
    the bare method name with parentheticals and any em-dash gloss removed.

Shortening never cuts mid-word, never leaves an unclosed parenthetical, and
never ends on a preposition, conjunction or article; see `tidy` and `cut_to`.

Usage:
  python3 evaluation/build_openai_metadata.py --write   # regenerate all files
  python3 evaluation/build_openai_metadata.py --check   # exit 1 if any is stale
"""

import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

HEADER = "# Generated by evaluation/build_openai_metadata.py — do not edit by hand.\n"

# Blurb budget. MIN keeps a blurb informative ("Runs a horizon scan" alone is
# not); MAX keeps it one line in a skill list.
MIN_SHORT = 30
MAX_SHORT = 120

# Words a blurb must never end on after a hard truncation: cutting before their
# object leaves the phrase hanging ("... compares it against the").
DANGLING_TAIL = {
    "a", "about", "according", "across", "after", "against", "an", "and", "as",
    "at", "based", "be", "been", "before", "being", "between", "both", "but",
    "by", "can", "could", "did", "do", "does", "during", "either", "for",
    "from", "had", "has", "have", "in", "including", "into", "is", "its",
    "may", "might", "must", "neither", "of", "on", "onto", "or", "over", "per",
    "should", "so", "than", "that", "the", "their", "then", "these", "this",
    "those", "through", "to", "under", "up", "upon", "using", "via", "was",
    "were", "when", "which", "while", "will", "with", "within", "without",
    "would",
    # determiners and quantifiers: they always precede the noun that was cut
    "another", "any", "each", "every", "no", "other", "several", "some", "such",
}

# A truncation usually lands part-way through a list. A trailing item this short
# is a fragment, not a thought, so the blurb falls back to the comma before it.
FRAGMENT_WORDS = 2

# Clause separators a blurb may stop at. A comma is deliberately absent: it
# usually separates list items ("a design, architecture, or business-model
# problem"), and stopping there truncates the thought.
CLAUSE_SEPARATORS = [r"\s+[—–]\s+", r":\s+", r";\s+"]


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def frontmatter_block(text):
    m = re.match(r"\A---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise ValueError("missing YAML frontmatter")
    return m.group(1)


def scalar(block, pattern):
    """Read a single-line YAML scalar, unwrapping it only if it is fully quoted.

    Stopping at the first quote character (the previous behaviour) silently
    truncated every method containing an apostrophe or a quoted phrase —
    "Lipinski's rule of five", 'Analysis (with "What If?" Analysis)'.
    """
    m = re.search(pattern, block, re.M)
    if not m:
        return ""
    value = m.group(1).strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        try:
            return json.loads(value) if value[0] == '"' else value[1:-1]
        except ValueError:
            return value[1:-1]
    return value


def skill_properties(text):
    """Return (name, method, description) from the SKILL.md frontmatter."""
    block = frontmatter_block(text)
    name = scalar(block, r"^name:\s*(.+?)\s*$")
    if not name:
        raise ValueError("missing frontmatter name")
    method = scalar(block, r"^\s{2}method:\s*(.+?)\s*$")
    description = scalar(block, r"^description:\s*(.+?)\s*$")
    return name, method, description


OPENERS = {"(": ")", "[": "]", "{": "}"}
CLOSERS = {v: k for k, v in OPENERS.items()}


def drop_unclosed(text):
    """Remove a trailing bracketed or backticked fragment that never closes."""
    stack, cut = [], None
    for i, ch in enumerate(text):
        if ch in OPENERS:
            if not stack:
                cut = i
            stack.append(ch)
        elif ch in CLOSERS and stack and stack[-1] == CLOSERS[ch]:
            stack.pop()
            if not stack:
                cut = None
    if stack and cut is not None:
        text = text[:cut]
    if text.count("`") % 2:
        text = text[: text.rindex("`")]
    return text


def _balanced(text):
    """True when every bracket and backtick in `text` is closed."""
    return (text.count("`") % 2 == 0
            and all(text.count(o) == text.count(c) for o, c in OPENERS.items()))


def _strip_edges(text):
    text = re.sub(r"\s+", " ", text).strip()
    return re.sub(r"[\s.,;:—–-]+$", "", text).strip()


def _drop_dangling_words(text):
    parts = text.split(" ")
    while parts and (parts[-1].strip(".,;:").lower() in DANGLING_TAIL
                     or parts[-1].endswith(("\u2019", "'"))):
        parts.pop()
    out = _strip_edges(" ".join(parts))
    head, comma, tail = out.rpartition(",")
    if comma and head.strip() and _balanced(head) and len(tail.split()) <= FRAGMENT_WORDS:
        return _drop_dangling_words(_strip_edges(head))
    return out


def tidy(text):
    """Normalise whitespace, close off any hanging fragment, trim punctuation.

    A clause that legitimately ends on a preposition keeps it ("every premise a
    conclusion rests on"); one left hanging because an unclosed bracket was
    removed does not.
    """
    closed = drop_unclosed(text)
    out = _strip_edges(closed)
    return _drop_dangling_words(out) if closed != text else out


def trim_dangling(text):
    """Tidy, then drop trailing words that need the object the cut removed."""
    return _drop_dangling_words(tidy(text))


def cut_to(text, limit):
    """Truncate at a word boundary and trim the tail. Never cuts mid-word."""
    if len(tidy(text)) <= limit:
        return tidy(text)
    head = text[: limit + 1]
    if " " in head:
        head = head.rsplit(" ", 1)[0]
    return trim_dangling(head)


def first_sentence(text):
    return re.split(r"(?<=[.!?])\s+(?=[A-Z\"])", text.strip())[0] if text.strip() else ""


def clause_prefixes(sentence):
    """Prefixes of `sentence` cut at clause separators, shortest first."""
    cuts = set()
    for pattern in CLAUSE_SEPARATORS:
        for m in re.finditer(pattern, sentence):
            cuts.add(m.start())
    out = [sentence[:i] for i in sorted(cuts)]
    out.append(sentence)
    return out


def short_description(description, method, display):
    """The shortest clause of the skill's own description that still informs.

    Clause prefixes grow left to right, so the first one that is at least
    MIN_SHORT long, within MAX_SHORT, and does not end on a word needing an
    object is the best stopping point. Only when no clause qualifies is the text
    truncated.
    """
    prefixes = [tidy(p) for p in clause_prefixes(first_sentence(description))]
    fitting = [p for p in prefixes if len(p) <= MAX_SHORT]
    usable = [p for p in fitting if len(p) >= MIN_SHORT and _drop_dangling_words(p) == p]
    if usable:
        return usable[0]
    overrunning = [p for p in prefixes if len(p) > MAX_SHORT]
    if overrunning:
        return cut_to(overrunning[0], MAX_SHORT)
    if fitting:
        return _drop_dangling_words(fitting[-1])
    # No description to work from: fall back to the method as a noun phrase.
    return cut_to(tidy(method or display), MAX_SHORT)


def bare_method(method, display):
    """The method as a plain noun phrase: no parenthetical, no em-dash gloss."""
    value = re.sub(r"\s*\([^()]*\)", " ", method or display)
    value = re.split(r"\s+[—–]\s+", value)[0]
    value = tidy(value)
    # Sentence-medial: "apply the Pyramid Principle", not "apply The Pyramid ...".
    if value.startswith("The "):
        value = "the " + value[4:]
    return value or display


def generated_text(skill_dir):
    text = read(os.path.join(skill_dir, "SKILL.md"))
    name, method, description = skill_properties(text)
    title = re.search(r"^#\s+(.+)$", text, re.M)
    display = title.group(1).strip() if title else name.replace("-", " ").title()
    short = short_description(description, method, display)
    prompt = "Use $%s to apply %s to the material I provide." % (name, bare_method(method, display))
    # JSON string syntax is a valid YAML double-quoted scalar and handles every
    # punctuation mark in method names deterministically.
    return (
        HEADER
        + "interface:\n"
        "  display_name: %s\n"
        "  short_description: %s\n"
        "  default_prompt: %s\n"
        % (json.dumps(display, ensure_ascii=False), json.dumps(short, ensure_ascii=False),
           json.dumps(prompt, ensure_ascii=False))
    )


def iter_skills(root):
    skills_dir = os.path.join(root, "skills")
    for name in sorted(os.listdir(skills_dir)):
        # Leading underscore = contributor scaffolding (skills/_TEMPLATE), not a skill.
        if name.startswith("_"):
            continue
        skill_dir = os.path.join(skills_dir, name)
        if os.path.isfile(os.path.join(skill_dir, "SKILL.md")):
            yield name, skill_dir


def copy_problems(short, prompt):
    """Hard guarantees on the two generated sentences (used by --selftest)."""
    problems = []
    for label, value in (("short_description", short), ("default_prompt", prompt)):
        if value.count("(") != value.count(")"):
            problems.append("%s has an unbalanced parenthesis: %r" % (label, value))
        if value.count("`") % 2 or value.count("[") != value.count("]"):
            problems.append("%s has an unbalanced bracket or backtick: %r" % (label, value))
        tail = value.rstrip(".").rsplit(" ", 1)[-1].strip(".,;:")
        if tail.lower() in DANGLING_TAIL or tail.endswith(("\u2019", "'")):
            problems.append("%s ends on a dangling word %r" % (label, tail))
        if re.search(r"[\s,;:—–]$", value):
            problems.append("%s ends on punctuation: %r" % (label, value))
    if not prompt.endswith("to the material I provide."):
        problems.append("default_prompt is not the canonical sentence: %r" % prompt)
    if len(short) > MAX_SHORT:
        problems.append("short_description exceeds %d chars: %r" % (MAX_SHORT, short))
    return problems


def selftest():
    checks = 0
    cases = [
        # (input, limit, expected) — shortening must not cut mid-word or leave "(".
        ("Apply AMSTAR 2 (A MeaSurement Tool to Assess systematic Reviews, version 2)", 60,
         "Apply AMSTAR 2"),
        ("Pools the effect sizes of several comparable studies", 30, "Pools the effect sizes"),
        ("Scores forecasts and compares it against the", 40,
         "Scores forecasts and compares it"),
        ("Tags every claim as either `[validated, {source}]` or `[assumption", 200,
         "Tags every claim as either `[validated, {source}]`"),
    ]
    for text, limit, expected in cases:
        got = cut_to(text, limit)
        assert got == expected, (text, got, expected)
        checks += 1
    assert drop_unclosed("a (b c") == "a "
    assert drop_unclosed("a (b) c") == "a (b) c"
    assert drop_unclosed("a `[b") == "a "
    # A clause that genuinely ends on a preposition keeps it; a cut one does not.
    assert tidy("Surfaces every premise a conclusion rests on") \
        == "Surfaces every premise a conclusion rests on"
    assert trim_dangling("Revises it using the odds form of Bayes\u2019") \
        == "Revises it using the odds form"
    checks += 5
    assert bare_method("The Pyramid Principle (governing thought)", "x") == "the Pyramid Principle"
    assert bare_method('High-Impact/Low-Probability Analysis (with "What If?" Analysis)', "x") \
        == "High-Impact/Low-Probability Analysis"
    assert bare_method("Estimative language — words of estimative probability", "x") == "Estimative language"
    checks += 3
    print("selftest OK (%d checks)" % checks)
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", default=os.path.dirname(HERE))
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    if args.selftest:
        return selftest()
    failures = 0
    count = 0
    for name, skill_dir in iter_skills(os.path.abspath(args.root)):
        count += 1
        expected = generated_text(skill_dir)
        path = os.path.join(skill_dir, "agents", "openai.yaml")
        short = json.loads(re.search(r"^  short_description: (.+)$", expected, re.M).group(1))
        prompt = json.loads(re.search(r"^  default_prompt: (.+)$", expected, re.M).group(1))
        for problem in copy_problems(short, prompt):
            failures += 1
            print("FAIL skills/%s: %s" % (name, problem))
        if args.write:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(expected)
        elif not os.path.isfile(path):
            failures += 1
            print("FAIL skills/%s: missing agents/openai.yaml" % name)
        elif read(path) != expected:
            failures += 1
            print("FAIL skills/%s/agents/openai.yaml: generated metadata is stale" % name)
    if failures:
        print("%d OpenAI metadata check(s) failed" % failures)
        return 1
    print("OK: %d skills have current agents/openai.yaml metadata" % count)
    return 0


if __name__ == "__main__":
    sys.exit(main())
